//! Inhalte erkennen, die Passwortmanager als vertraulich markieren. KeePassXC, KeePass und andere
//! legen zum kopierten Passwort eine Markierung in die Zwischenablage, damit Verlauf, Cloud-Abgleich
//! und Zwischenablage-Programme es nicht aufheben. Qross teilt solche Inhalte nicht mit anderen
//! Rechnern (siehe [`crate::Clipboard::concealed`]).
//!
//! Hier stehen nur die Regeln, ohne Aufrufe ans System, damit sie überall testbar sind. Gelesen
//! werden die Markierungen in `win::clipboard` (registrierte Formate), `mac::pasteboard`
//! (Pasteboard-Typen) und `clipboard_hint` (MIME-Typen unter X11 und Wayland).

/// Wie der Inhalt einer Markierung zu lesen ist
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Rule {
    /// Schon das Vorhandensein zählt, der Inhalt ist beliebig
    Present,
    /// Der Text „secret“
    Secret,
}

impl Rule {
    /// Kennzeichnet die Markierung den Inhalt als vertraulich? `data` ist `None`, wenn die
    /// Markierung vorliegt, ihr Inhalt aber nicht lesbar ist – dann im Zweifel ja.
    pub fn conceals(self, data: Option<&[u8]>) -> bool {
        let Some(data) = data else { return true };
        match self {
            Rule::Present => true,
            Rule::Secret => data.trim_ascii_start().starts_with(b"secret"),
        }
    }
}

/// Eine Markierung: Name des Formats (Windows), des Pasteboard-Typs (macOS) bzw. des MIME-Typs
/// (Linux) und wie ihr Inhalt zu lesen ist
pub type Marker = (&'static str, Rule);

/// Windows: das registrierte Format, mit dem Passwortmanager (KeePass, KeePassXC, 1Password)
/// Zwischenablage-Programme ausschließen, dazu eine ältere Absprache unter diesen Programmen.
/// `CanIncludeInClipboardHistory` und `CanUploadToCloudClipboard` mit 0 zählen nicht: Sie halten
/// einen Inhalt nur aus dem Verlauf (Win+V) und der Cloud heraus, und Chrome setzt sie etwa für
/// Kopien aus einem Inkognito-Fenster, auch für eine einfache URL. Passwortmanager setzen sie
/// zusätzlich zum ersten Format.
pub const WINDOWS: &[Marker] =
    &[("ExcludeClipboardContentFromMonitorProcessing", Rule::Present), ("Clipboard Viewer Ignore", Rule::Present)];

/// macOS: Pasteboard-Typen nach nspasteboard.org, auch die älteren Namen, die dort stehen.
/// `org.nspasteboard.AutoGeneratedType` gehört nicht dazu: Er sagt nur, dass ein Programm den
/// Inhalt ohne Zutun des Nutzers abgelegt hat, nicht dass er vertraulich ist – er bleibt der
/// aktuelle Inhalt und wird geteilt.
pub const MACOS: &[Marker] = &[
    // vertraulich, etwa ein Passwort (KeePassXC, 1Password, Strongbox)
    ("org.nspasteboard.ConcealedType", Rule::Present),
    ("com.agilebits.onepassword", Rule::Present),
    // nur für Sekunden da, etwa ein Textbaustein beim Einfügen
    ("org.nspasteboard.TransientType", Rule::Present),
    ("de.petermaurer.TransientPasteboardType", Rule::Present),
    ("com.typeit4me.clipping", Rule::Present),
    ("Pasteboard generator type", Rule::Present),
];

/// Linux (X11 und Wayland): der Hinweis von KDE, den KeePassXC setzt und Klipper beachtet
pub const LINUX: &[Marker] = &[("x-kde-passwordManagerHint", Rule::Secret)];

/// Erste Markierung aus `markers`, die den Inhalt als vertraulich kennzeichnet. `lookup` sagt je
/// Name: `None` fehlt, `Some(None)` liegt vor, ist aber nicht lesbar, `Some(Some(bytes))` liegt
/// mit diesem Inhalt vor.
pub fn find(markers: &[Marker], mut lookup: impl FnMut(&str) -> Option<Option<Vec<u8>>>) -> Option<&'static str> {
    markers
        .iter()
        .find(|(name, rule)| lookup(name).is_some_and(|data| rule.conceals(data.as_deref())))
        .map(|(name, _)| *name)
}

/// Wie [`find`] für Systeme, die nur sagen, welche Typen vorliegen (macOS)
pub fn find_in_types<S: AsRef<str>>(markers: &[Marker], types: &[S]) -> Option<&'static str> {
    find(markers, |name| types.iter().any(|t| t.as_ref() == name).then_some(None))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Zwischenablage mit diesen Formaten und Inhalten (`None`: nicht lesbar)
    fn clipboard<'a>(formats: &'a [(&'a str, Option<&'a [u8]>)]) -> impl FnMut(&str) -> Option<Option<Vec<u8>>> + 'a {
        |name| formats.iter().find(|(n, _)| *n == name).map(|(_, data)| data.map(<[u8]>::to_vec))
    }

    #[test]
    fn keepassxc_on_windows_is_concealed() {
        let formats: &[(&str, Option<&[u8]>)] = &[
            ("CF_UNICODETEXT", Some(b"g\0e\0h\0e\0i\0m\0")),
            ("ExcludeClipboardContentFromMonitorProcessing", Some(b"1")),
            ("CanIncludeInClipboardHistory", Some(&[0; 4])),
            ("CanUploadToCloudClipboard", Some(&[0; 4])),
        ];
        assert_eq!(find(WINDOWS, clipboard(formats)), Some("ExcludeClipboardContentFromMonitorProcessing"));
    }

    #[test]
    fn each_windows_format_counts_on_its_own() {
        for name in ["ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore"] {
            assert_eq!(find(WINDOWS, clipboard(&[(name, Some(&[]))])), Some(name), "{name}");
            assert_eq!(find(WINDOWS, clipboard(&[(name, None)])), Some(name), "{name}, nicht lesbar");
        }
    }

    #[test]
    fn a_url_from_chrome_outside_the_history_is_shared() {
        // Gemeldet: eine aus Chrome kopierte URL blieb hier, markiert mit „CanIncludeInClipboardHistory“
        let chrome: &[(&str, Option<&[u8]>)] = &[
            ("CF_UNICODETEXT", Some(b"h\0t\0t\0p\0s\0:\0/\0/\0")),
            ("CanIncludeInClipboardHistory", Some(&[0, 0, 0, 0])),
            ("CanUploadToCloudClipboard", Some(&[0, 0, 0, 0])),
        ];
        assert_eq!(find(WINDOWS, clipboard(chrome)), None);
        assert_eq!(find(WINDOWS, clipboard(&[("CanIncludeInClipboardHistory", None)])), None);
        assert_eq!(find(WINDOWS, clipboard(&[("CF_UNICODETEXT", Some(b"a\0"))])), None);
    }

    #[test]
    fn unreadable_markers_count_as_concealed() {
        assert_eq!(find(LINUX, clipboard(&[("x-kde-passwordManagerHint", None)])), Some("x-kde-passwordManagerHint"));
    }

    #[test]
    fn kde_hint_needs_secret() {
        assert_eq!(find(LINUX, clipboard(&[("x-kde-passwordManagerHint", Some(b"secret"))])), Some("x-kde-passwordManagerHint"));
        assert_eq!(find(LINUX, clipboard(&[("x-kde-passwordManagerHint", Some(b" secret\n"))])), Some("x-kde-passwordManagerHint"));
        assert_eq!(find(LINUX, clipboard(&[("x-kde-passwordManagerHint", Some(b"public"))])), None);
        assert_eq!(find(LINUX, clipboard(&[("text/plain", Some(b"secret"))])), None);
    }

    #[test]
    fn mac_concealed_and_transient_types() {
        let keepassxc = ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"];
        assert_eq!(find_in_types(MACOS, &keepassxc), Some("org.nspasteboard.ConcealedType"));
        let snippet = ["public.utf8-plain-text", "org.nspasteboard.TransientType"];
        assert_eq!(find_in_types(MACOS, &snippet), Some("org.nspasteboard.TransientType"));
        assert_eq!(find_in_types(MACOS, &["com.agilebits.onepassword"]), Some("com.agilebits.onepassword"));
    }

    #[test]
    fn mac_auto_generated_content_is_shared() {
        let types = ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.source"];
        assert_eq!(find_in_types(MACOS, &types), None);
        assert_eq!(find_in_types(MACOS, &["com.apple.is-remote-clipboard", "public.png"]), None);
    }
}
