const REVERSE_ONLY: &[(u16, u16)] = &[
    (0x32, 0x2A), // Non-US # → Backslash-Position
];

/// HID-Usages, die es am Mac nicht gibt
pub const UNMAPPED: &[u16] = &[0x46, 0x47, 0x48, 0x70, 0x71, 0x72, 0x73, 0x8A];

pub fn mac_from_hid(key: KeyCode) -> Option<u16> {
    TABLE.iter().chain(REVERSE_ONLY).find(|(hid, _)| *hid == key.0).map(|&(_, code)| code)
}

pub fn hid_from_mac(code: u16) -> Option<KeyCode> {
    TABLE.iter().find(|(_, c)| *c == code).map(|&(hid, _)| KeyCode(hid))
}

/// Modifier-Tasten melden macOS nicht als KeyDown/KeyUp, sondern als FlagsChanged.
pub fn is_modifier(code: u16) -> bool {
    matches!(code, 0x36..=0x3E)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn table_is_unique_and_roundtrips() {
        let codes: HashSet<_> = TABLE.iter().map(|(_, c)| c).collect();
        let hids: HashSet<_> = TABLE.iter().map(|(h, _)| h).collect();
        assert_eq!(codes.len(), TABLE.len());
        assert_eq!(hids.len(), TABLE.len());
        for &(hid, code) in TABLE {
            assert_eq!(hid_from_mac(code), Some(KeyCode(hid)));
        }
    }

    #[test]
    fn covers_windows_keys_except_pc_only_ones() {
        for hid in 0..=0xFFu16 {
            let key = KeyCode(hid);
            let on_windows = crate::keymap_windows::windows_from_hid(key).is_some();
            let expected = on_windows && !UNMAPPED.contains(&hid);
            assert_eq!(mac_from_hid(key).is_some(), expected, "HID {hid:#04x}");
        }
    }

    #[test]
    fn modifiers_are_recognised() {
        for hid in 0xE0..=0xE7u16 {
            assert!(is_modifier(mac_from_hid(KeyCode(hid)).unwrap()), "HID {hid:#04x}");
        }
        assert!(!is_modifier(mac_from_hid(KeyCode::A).unwrap()));
    }
}
